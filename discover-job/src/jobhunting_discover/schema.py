from collections.abc import Mapping

# Job boards offer these Date posted windows. A window of N days uses the narrowest one that covers it:
# LinkedIn's URL takes these exact seconds; arbitrary seconds were never verified (2026-11-08).
DATE_POSTED = ((1, "Past 24 hours", 86400), (7, "Past week", 604800), (30, "Past month", 2592000))


def date_posted(days: int) -> tuple[str, int | None]:
    """The board option and its seconds covering the last `days` days; beyond 30 days there is no date filter."""
    return next(((label, seconds) for limit, label, seconds in DATE_POSTED if days <= limit), ("Any time", None))


# `search_id` is minted by the worker up front; `time` is always generated by log_search.
#
# `outcome` is required on every call, always — a `result_count: 0` alone
# does not say whether the search genuinely ran and found nothing, or never
# completed at all (a down ATS, no central job board, a CAPTCHA block).
# Leaving that ambiguous is a silent-failure risk: a future search would see
# "already checked" and skip a source that was never actually checked.
REQUIRED_SEARCH_INPUT = ("source", "query", "prompt", "result_count", "outcome")
SEARCH_INPUT_FIELDS = frozenset((*REQUIRED_SEARCH_INPUT, "search_id"))


def validate_search_input(entry: Mapping[str, str]) -> dict[str, str]:
    unknown = set(entry) - SEARCH_INPUT_FIELDS
    if unknown:
        raise ValueError(f"unexpected search fields: {', '.join(sorted(unknown))}")

    missing = [
        field for field in REQUIRED_SEARCH_INPUT
        if not isinstance(entry.get(field), str) or not entry[field].strip()
    ]
    if missing:
        raise ValueError(f"missing required search fields: {', '.join(missing)}")

    return {key: value for key, value in entry.items()}
